'use strict';
/*
 * Client-side Portainer stack generator for chatgpt-youtube-mcp.
 *
 * Privacy contract: everything runs in this page. No fetch, no XHR, no
 * WebSocket, no storage APIs, no cookies, no URL parameters for values,
 * no telemetry. Secrets and the generated YAML exist only in page memory
 * and the visible DOM fields. See the CSP in index.html.
 *
 * The generated YAML mirrors generators/generate_docker-compose_for_ChatGPT_MCP.sh
 * exactly; equivalence is enforced by tests/test_generator_equivalence.py.
 */

// Fixed images (parity with the Bash/PowerShell generators).
var MCP_IMAGE_BASE = 'ghcr.io/dracoform/chatgpt-youtube-mcp';
var TUNNEL_IMAGE_BASE = 'ghcr.io/dracoform/openai-mcp-tunnel';

// Current Google API key format: AIza + 35 chars from [A-Za-z0-9_-].
var GOOGLE_KEY_PATTERN = /^AIza[A-Za-z0-9_-]{35}$/;
// OpenAI secret keys currently start with sk- (sk-proj-, sk-svcacct-, ...).
var OPENAI_KEY_PREFIX = /^sk-/;
var TUNNEL_ID_PATTERN = /^tunnel_[A-Za-z0-9_-]+$/;
var LANGUAGES_PATTERN = /^[A-Za-z0-9_-]+(,[A-Za-z0-9_-]+)*$/;

function $(id) { return document.getElementById(id); }

function redactForDiagnostics(value) {
  // Never log or expose secret material, even in error paths.
  return value ? '(value withheld)' : '(empty)';
}

/* ---------------------------------------------------------- masking ---- */

// Length-preserving mask: every character X except the final four; values
// of four characters or fewer are fully masked.
function maskSecret(value) {
  var length = value.length;
  if (length <= 4) {
    return new Array(length + 1).join('X');
  }
  // Array(n + 1).join('X') yields exactly n 'X' characters.
  return new Array(length - 4 + 1).join('X') + value.slice(-4);
}

// Reject control characters (CR, LF, NUL, C0/C1) and edge whitespace.
function secretHasControlCharsOrEdgeWhitespace(value) {
  if (value !== value.trim()) { return true; }
  for (var i = 0; i < value.length; i++) {
    var code = value.charCodeAt(i);
    if (code < 32 || (code >= 127 && code <= 159)) { return true; }
  }
  return false;
}

/* ------------------------------------------------------------ YAML ----- */

function yamlQuote(value) {
  return "'" + String(value).replace(/'/g, "''") + "'";
}

function buildYaml(input) {
  var lines = [];
  lines.push('# Generated by the chatgpt-youtube-mcp web generator. Contains secrets; restrict access.');
  lines.push('services:');
  lines.push('  youtube-mcp:');
  lines.push('    image: ' + yamlQuote(MCP_IMAGE_BASE + ':' + input.mcpTag));
  lines.push('    restart: unless-stopped');
  lines.push('    environment:');
  lines.push("      MCP_TRANSPORT: 'streamable-http'");
  lines.push("      MCP_HOST: '0.0.0.0'");
  lines.push("      MCP_PORT: '8765'");
  lines.push('      YOUTUBE_API_KEY: ' + yamlQuote(input.youtubeApiKey));
  lines.push('      YOUTUBE_ENABLE_YTDLP: ' + yamlQuote(input.enableYtdlp ? 'true' : 'false'));
  lines.push('      YOUTUBE_TRANSCRIPT_MAX_CHARS: ' + yamlQuote(input.maxChars));
  lines.push('      YOUTUBE_DEFAULT_LANGUAGES: ' + yamlQuote(input.languages));
  lines.push('    expose:');
  lines.push("      - '8765'");
  lines.push('    read_only: true');
  lines.push('    tmpfs:');
  lines.push('      - /tmp:size=64m');
  lines.push('    cap_drop:');
  lines.push('      - ALL');
  lines.push('    security_opt:');
  lines.push('      - no-new-privileges:true');
  lines.push('    networks:');
  lines.push('      - youtube-mcp-internal');
  lines.push('');
  lines.push('  openai-tunnel:');
  lines.push('    image: ' + yamlQuote(TUNNEL_IMAGE_BASE + ':' + input.tunnelTag));
  lines.push('    restart: unless-stopped');
  lines.push('    environment:');
  lines.push('      CONTROL_PLANE_TUNNEL_ID: ' + yamlQuote(input.tunnelId));
  lines.push('      CONTROL_PLANE_API_KEY: ' + yamlQuote(input.runtimeApiKey));
  lines.push("      MCP_SERVER_URL: 'http://youtube-mcp:8765/mcp'");
  if (input.httpProxy) {
    lines.push('      HTTPS_PROXY: ' + yamlQuote(input.httpProxy));
    lines.push("      NO_PROXY: 'youtube-mcp,localhost,127.0.0.1'");
  }
  lines.push('    depends_on:');
  lines.push('      youtube-mcp:');
  lines.push('        condition: service_healthy');
  lines.push('    read_only: true');
  lines.push('    tmpfs:');
  lines.push('      - /tmp:size=16m');
  lines.push('    cap_drop:');
  lines.push('      - ALL');
  lines.push('    security_opt:');
  lines.push('      - no-new-privileges:true');
  lines.push('    stop_grace_period: 30s');
  lines.push('    networks:');
  lines.push('      - youtube-mcp-internal');
  lines.push('');
  lines.push('networks:');
  lines.push('  youtube-mcp-internal:');
  lines.push('    driver: bridge');
  return lines.join('\n') + '\n';
}

/* --------------------------------------------------------- review UI --- */

function showReview(reviewId, maskId, lengthId, value, label) {
  var review = $(reviewId);
  review.classList.remove('hidden');
  $(maskId).textContent = maskSecret(value);
  $(lengthId).textContent = String(value.length);
  return label + ' received:\n' + maskSecret(value) + '\nLength: ' + value.length + ' characters';
}

function hideReview(reviewId) {
  $(reviewId).classList.add('hidden');
}

/* ----------------------------------------------------- secret state ---- */

// Confirmed secret values live only in these variables (page memory).
var confirmed = { youtubeApiKey: null, runtimeApiKey: null };

function confirmYouTubeKey(onDone) {
  var value = $('youtube_api_key').value;
  if (value === '') {
    showReview('yt-review', 'yt-mask', 'yt-length', '', '');
    if (window.confirm(
        'No YouTube API key was entered.\n\n' +
        'Continue without a YouTube API key?')) {
      confirmed.youtubeApiKey = '';
      hideReview('yt-review');
      onDone();
    } else {
      hideReview('yt-review');
      $('youtube_api_key').focus();
    }
    return;
  }
  if (secretHasControlCharsOrEdgeWhitespace(value)) {
    window.alert(
      'The value contains control characters or leading/trailing whitespace.\n' +
      'Please re-enter it.');
    hideReview('yt-review');
    $('youtube_api_key').focus();
    return;
  }
  showReview('yt-review', 'yt-mask', 'yt-length', value, 'YouTube API key');
  var length = value.length;
  var messages = [
    'YouTube API key received:\n' + maskSecret(value) +
      '\nLength: ' + length + ' characters\n\nUse this value?'
  ];
  if (!GOOGLE_KEY_PATTERN.test(value)) {
    messages.push(
      'Warning: this value does not match the expected Google API key format ' +
      '(AIza followed by 35 characters).\n\n' +
      'Possible cause: the key was pasted twice — check the displayed length.');
  }
  if (window.confirm(messages.join('\n\n'))) {
    if (!GOOGLE_KEY_PATTERN.test(value)) {
      if (!window.confirm(
          'Use this non-standard value anyway?\n' +
          '(Only confirm if you know your key format is correct.)')) {
        $('youtube_api_key').focus();
        return;
      }
    }
    confirmed.youtubeApiKey = value;
    hideReview('yt-review');
    onDone();
  } else {
    hideReview('yt-review');
    $('youtube_api_key').focus();
  }
}

function confirmRuntimeKey(onDone) {
  var value = $('runtime_api_key').value;
  if (value === '' || secretHasControlCharsOrEdgeWhitespace(value)) {
    window.alert(
      value === ''
        ? 'An OpenAI Runtime API key is required.'
        : 'The value contains control characters or leading/trailing whitespace.\n' +
          'Please re-enter it.');
    hideReview('rt-review');
    $('runtime_api_key').focus();
    return;
  }
  showReview('rt-review', 'rt-mask', 'rt-length', value, 'OpenAI Runtime API key');
  var messages = [
    'OpenAI Runtime API key received:\n' + maskSecret(value) +
      '\nLength: ' + value.length + ' characters\n\nUse this value?'
  ];
  if (!OPENAI_KEY_PREFIX.test(value)) {
    messages.push(
      'Warning: this value does not start with a recognized OpenAI key prefix (sk-).');
  }
  if (window.confirm(messages.join('\n\n'))) {
    if (!OPENAI_KEY_PREFIX.test(value)) {
      if (!window.confirm(
          'Use this value without a recognized prefix anyway?\n' +
          '(Only confirm if you know your key format is correct.)')) {
        $('runtime_api_key').focus();
        return;
      }
    }
    confirmed.runtimeApiKey = value;
    hideReview('rt-review');
    onDone();
  } else {
    hideReview('rt-review');
    $('runtime_api_key').focus();
  }
}

/* -------------------------------------------------------- main flow ---- */

function showError(message) {
  var el = $('form-error');
  el.textContent = message;
  el.classList.remove('hidden');
}

function clearError() {
  var el = $('form-error');
  el.textContent = '';
  el.classList.add('hidden');
}

function generateFromConfirmed() {
  clearError();
  var consent = $('ytdlp_consent').value.trim().toUpperCase();
  if ($('enable_ytdlp_true').checked) {
    if (consent === '') {
      showError('yt-dlp is enabled: the [CONDITIONAL] consent (type JA) is required.');
      $('ytdlp_consent').focus();
      return;
    }
    if (consent !== 'JA') {
      showError('Consent must be exactly JA to enable the unofficial yt-dlp fallback.');
      $('ytdlp_consent').focus();
      return;
    }
  }

  var tunnelId = $('tunnel_id').value.trim();
  if (!TUNNEL_ID_PATTERN.test(tunnelId)) {
    showError('The tunnel ID must start with tunnel_ (example: tunnel_0123456789abcdef).');
    $('tunnel_id').focus();
    return;
  }

  var runtimeKey = confirmed.runtimeApiKey;
  if (!runtimeKey) {
    showError('The OpenAI Runtime API key must be entered and confirmed first.');
    return;
  }
  if (secretHasControlCharsOrEdgeWhitespace(runtimeKey)) {
    showError('The confirmed runtime API key contains invalid characters. Please re-enter it.');
    return;
  }

  var languages = $('languages').value.trim();
  if (!LANGUAGES_PATTERN.test(languages)) {
    showError('Invalid language list. Example: de,en');
    $('languages').focus();
    return;
  }

  var maxChars = $('max_chars').value.trim();
  if (!/^[0-9]+$/.test(maxChars) || +maxChars < 1000 || +maxChars > 500000) {
    showError('The transcript limit must be a number between 1000 and 500000.');
    $('max_chars').focus();
    return;
  }

  var mcpTag = $('mcp_tag').value.trim();
  var tunnelTag = $('tunnel_tag').value.trim();
  if (!mcpTag || !tunnelTag) {
    showError('Both image tags are required.');
    return;
  }

  var yaml = buildYaml({
    mcpTag: mcpTag,
    tunnelTag: tunnelTag,
    youtubeApiKey: confirmed.youtubeApiKey || '',
    enableYtdlp: $('enable_ytdlp_true').checked,
    languages: languages,
    maxChars: maxChars,
    tunnelId: tunnelId,
    runtimeApiKey: runtimeKey,
    httpProxy: $('http_proxy').value.trim(),
  });

  var output = $('yaml-output');
  output.value = yaml;
  $('output').classList.remove('hidden');
  $('btn-copy').disabled = false;
  $('btn-select').disabled = false;
  $('output').scrollIntoView({ behavior: 'smooth', block: 'start' });
}

function onGenerate() {
  clearError();
  confirmYouTubeKey(function () {
    confirmRuntimeKey(generateFromConfirmed);
  });
}

/* -------------------------------------------------------- clipboard ---- */

function onCopy() {
  var output = $('yaml-output');
  var status = $('copy-status');
  function report(ok, fallbackHint) {
    status.textContent = ok
      ? 'YAML copied. Paste it into Portainer: Stacks -> Add stack -> Web editor.'
      : (fallbackHint ||
         'Copying failed. Select the YAML manually and copy with Ctrl/Cmd+C.');
    status.classList.add('ok');
    status.classList.remove('hidden');
  }
  if (navigator.clipboard && navigator.clipboard.writeText) {
    navigator.clipboard.writeText(output.value).then(
      function () { report(true); },
      function () { report(false); }
    );
  } else {
    // Legacy path without the async Clipboard API.
    output.focus();
    output.select();
    var ok = false;
    try { ok = document.execCommand('copy'); } catch (err) { ok = false; }
    report(ok);
  }
}

function onSelectAll() {
  var output = $('yaml-output');
  output.focus();
  output.select();
}

/* --------------------------------------------------------- clearing ---- */

function clearSensitiveData() {
  // Form fields
  var fields = document.querySelectorAll(
    '#generator-form input[type="text"], #generator-form input[type="password"]'
  );
  for (var i = 0; i < fields.length; i++) {
    if (fields[i].type === 'password') {
      fields[i].value = '';
    }
  }
  // Restore visible defaults (non-secret fields).
  $('mcp_tag').value = 'latest';
  $('tunnel_tag').value = '0.1.0';
  $('languages').value = 'de,en';
  $('max_chars').value = '60000';
  $('tunnel_id').value = '';
  $('http_proxy').value = '';
  $('ytdlp_consent').value = '';
  $('enable_ytdlp_true').checked = true;
  $('enable_ytdlp_false').checked = false;
  updateConsentVisibility();

  // Secret state and reviews
  confirmed.youtubeApiKey = null;
  confirmed.runtimeApiKey = null;
  hideReview('yt-review');
  hideReview('rt-review');
  resetShowToggle('yt-show', 'youtube_api_key');
  resetShowToggle('rt-show', 'runtime_api_key');

  // Generated YAML and UI references
  var output = $('yaml-output');
  output.value = '';
  $('btn-copy').disabled = true;
  $('btn-select').disabled = true;
  $('output').classList.add('hidden');
  $('copy-status').textContent = '';
  $('copy-status').classList.add('hidden');
  clearError();
}

function resetShowToggle(buttonId, inputId) {
  $(buttonId).textContent = 'Show';
  $(buttonId).setAttribute('aria-pressed', 'false');
  $(inputId).type = 'password';
}

function startOver() {
  clearSensitiveData();
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

/* ------------------------------------------------------ show/hide ------ */

function wireShowToggle(buttonId, inputId) {
  $(buttonId).addEventListener('click', function () {
    var input = $(inputId);
    var showing = input.type === 'text';
    input.type = showing ? 'password' : 'text';
    $(buttonId).textContent = showing ? 'Show' : 'Hide';
    $(buttonId).setAttribute('aria-pressed', showing ? 'false' : 'true');
  });
}

function updateConsentVisibility() {
  var field = $('consent-field');
  if ($('enable_ytdlp_true').checked) {
    field.classList.remove('hidden');
  } else {
    field.classList.add('hidden');
  }
}

/* ------------------------------------------------------- form guard ---- */

// The form exists only for semantics/accessibility; submission must never
// navigate the page (CSP form-action 'none' also blocks it server-side).
function blockSubmission(event) {
  event.preventDefault();
}

/* -------------------------------------------------------------- init --- */

function init() {
  wireShowToggle('yt-show', 'youtube_api_key');
  wireShowToggle('rt-show', 'runtime_api_key');
  $('btn-generate').addEventListener('click', onGenerate);
  $('btn-copy').addEventListener('click', onCopy);
  $('btn-select').addEventListener('click', onSelectAll);
  $('btn-clear').addEventListener('click', clearSensitiveData);
  $('btn-restart').addEventListener('click', startOver);
  $('generator-form').addEventListener('submit', blockSubmission);
  var radios = document.querySelectorAll('input[name="enable_ytdlp"]');
  for (var i = 0; i < radios.length; i++) {
    radios[i].addEventListener('change', updateConsentVisibility);
  }
  updateConsentVisibility();
}

